export function getTranslations(lang: string): Translations {
  return translations[lang] ?? translations[defaultLang];
}

export function getLanguageMeta(lang: string): LanguageMeta {
  return languages.find((item) => item.id === lang) ?? languages[0];
}

export function getLangFromPath(pathname: string): string {
  const segment = pathname.split('/').filter(Boolean)[0];
  if (segment && languages.some((item) => item.id === segment)) return segment;
  return defaultLang;
}
